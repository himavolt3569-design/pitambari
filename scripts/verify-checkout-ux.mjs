import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
try {
  const context=await browser.newContext({viewport:{width:1280,height:850},geolocation:{latitude:27.7172,longitude:85.3240},permissions:['geolocation']});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
  await page.locator('#product').scrollIntoViewIfNeeded();
  await page.locator('#product button:has-text("Buy Now")').click();
  const dialog=page.getByRole('dialog');await dialog.waitFor();await page.waitForTimeout(800);
  const before=await page.evaluate(()=>window.scrollY);
  const scroller=dialog.locator('.overflow-y-auto');
  const box=await scroller.boundingBox();await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.wheel(0,650);await page.waitForTimeout(700);
  assert.equal(await page.evaluate(()=>window.scrollY),before,'background stayed still');
  assert.ok(await scroller.evaluate(el=>el.scrollTop)>0,'modal itself scrolls');
  await scroller.evaluate(el=>el.scrollTop=0);
  await page.route('**/api/checkout/location',route=>route.fulfill({json:{ok:true,address:{province:'Bagmati',district:'Kathmandu',municipality:'Kathmandu',ward:'16',area:'Thamel',street:'Tridevi Marg'}}}));
  await page.getByRole('button',{name:'Use my current location'}).click();
  await page.waitForFunction(()=>document.querySelector('select')?.value==='Bagmati');
  assert.equal(await page.getByLabel('District').inputValue(),'Kathmandu');
  assert.equal(await page.getByLabel('Municipality or city').inputValue(),'Kathmandu');
  assert.equal(await page.getByLabel('Ward number').inputValue(),'16');
  await page.getByLabel('Area or tole').fill('Manual correction');
  assert.equal(await page.getByLabel('Area or tole').inputValue(),'Manual correction');
  await page.getByLabel('Province').selectOption('Gandaki');
  assert.equal(await page.getByLabel('District').inputValue(),'');
  assert.equal(await page.getByLabel('Area or tole').inputValue(),'');
  const quoteResponse=page.waitForResponse(r=>r.url().includes('/api/checkout/quote') && r.request().postDataJSON()?.district==='Kaski');
  await page.getByLabel('District').selectOption('Kaski');
  const quote=await (await quoteResponse).json();
  assert.equal(quote.ok,true);
  if(quote.deliveryMethods.length) await page.getByText(quote.deliveryMethods[0].name,{exact:true}).first().waitFor();
  else await page.getByText(/We do not currently deliver/).waitFor();
  await scroller.evaluate(el=>el.scrollTop=0);await page.screenshot({path:'.tmp/shots/checkout-new-desktop.png'});
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:'.tmp/shots/checkout-new-mobile.png'});
  assert.ok(await dialog.evaluate(el=>el.getBoundingClientRect().width)<=390);
  assert.ok(await scroller.evaluate(el=>el.scrollWidth<=el.clientWidth),'mobile checkout content fits without horizontal overflow');
  await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
  await page.mouse.move(200,400);await page.mouse.wheel(0,500);await page.waitForTimeout(900);
  assert.notEqual(await page.evaluate(()=>window.scrollY),before,'background resumes scrolling');
  assert.deepEqual(errors,[]);
  await page.unroute('**/api/checkout/location');
  const response=await context.request.post('http://localhost:3000/api/checkout/location',{data:{latitude:27.7172,longitude:85.3240}});
  const result=await response.json();
  console.log('Live reverse-geocoding:',response.status(),JSON.stringify(result));
  assert.equal(result.ok,true,'live reverse-geocoder works');
  assert.equal(result.address.province,'Bagmati');assert.equal(result.address.district,'Kathmandu');
  console.log('PASS checkout scrolling, location autofill, manual correction, delivery recalculation, mobile layout and live geocoding');
}finally{await browser.close();}
